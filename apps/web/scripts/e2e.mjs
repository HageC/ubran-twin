import { chromium } from "playwright-core";
import { readFile } from "node:fs/promises";

const browserPath = process.env.PLAYWRIGHT_BROWSER_PATH ?? (process.platform === "win32" ? "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe" : undefined);
const browser = await chromium.launch({ executablePath: browserPath, headless: true, args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.addInitScript(() => { if (!sessionStorage.getItem("study-test-started")) { localStorage.clear(); sessionStorage.setItem("study-test-started", "1"); } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(process.env.WEB_URL ?? "http://localhost:3000", { waitUntil: "domcontentloaded" });
  await page.getByRole("heading", { name: "Test a traffic change" }).waitFor();
  await page.getByRole("button", { name: "Browse areas" }).click();
  await page.getByRole("dialog", { name: "Choose a study area" }).getByRole("searchbox").fill("Vancouver");
  await page.getByRole("dialog", { name: "Choose a study area" }).getByRole("button", { name: /Vancouver · Downtown/ }).waitFor();
  if (await page.locator(".area-list button").count() !== 1) throw new Error("Area search did not narrow the published districts");
  await page.getByRole("button", { name: "Close area directory" }).click();
  if (await page.locator("#region-select").inputValue() !== "toronto-core") throw new Error("Expanded district is not the first-use default");
  await page.getByText(/652 mapped roads · 294 changeable/).waitFor();
  await page.getByRole("button", { name: "Run baseline", exact: true }).waitFor();
  await page.locator(".maplibregl-canvas").waitFor();
  if (await page.locator(".maplibregl-canvas").count() !== 1) throw new Error("MapLibre canvas did not render");
  const initialMapBox = await page.locator(".maplibregl-canvas").boundingBox();
  await page.waitForTimeout(800);
  const mapBeforeWheel = await page.locator(".maplibregl-canvas").screenshot();
  const scrollBeforeWheel = await page.evaluate(() => window.scrollY);
  await page.mouse.move(initialMapBox.x + initialMapBox.width / 2, initialMapBox.y + initialMapBox.height / 2);
  await page.mouse.wheel(0, -600);
  await page.waitForTimeout(700);
  const mapAfterWheel = await page.locator(".maplibregl-canvas").screenshot();
  if (mapBeforeWheel.equals(mapAfterWheel)) throw new Error("Mouse wheel did not zoom the map");
  if (Math.abs((await page.evaluate(() => window.scrollY)) - scrollBeforeWheel) > 2) throw new Error("Wheel over the map scrolled the page");
  await page.mouse.move(5, 200);
  await page.mouse.wheel(0, 500);
  await page.waitForFunction(() => window.scrollY > 20);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.locator(".coverage-note summary").getByText(/mapped roads · .*changeable/).waitFor();
  await page.getByRole("button", { name: "Browse areas" }).click();
  await page.getByRole("dialog", { name: "Choose a study area" }).getByRole("searchbox").fill("Nelson Street");
  const streetResult = page.locator(".area-road-results button").filter({ hasText: "Toronto · Financial District" }).first();
  await streetResult.waitFor();
  await streetResult.click();
  await page.waitForFunction(() => document.querySelector("#region-select")?.value === "toronto-demo");
  await page.locator(".map-selection strong").getByText("Nelson Street").waitFor();
  await page.locator("#region-select").selectOption("toronto-core");
  await page.locator("#region-select").selectOption("montreal-demo");
  await page.getByRole("heading", { name: "Test a traffic change" }).waitFor();
  if (await page.locator("#region-select").inputValue() !== "montreal-demo") throw new Error("District did not switch");
  await page.locator("#region-select").selectOption("toronto-demo");
  await page.locator(".coverage-note summary").getByText(/mapped roads · 29 changeable/).waitFor();
  await page.waitForTimeout(900); // The district camera transition takes 500 ms.
  const mapBox = await page.locator(".maplibregl-canvas").boundingBox();
  let mapSelected = false;
  for (const y of [0.3, 0.45, 0.6, 0.75]) {
    for (const x of [0.25, 0.4, 0.55, 0.7]) {
      await page.mouse.click(mapBox.x + mapBox.width * x, mapBox.y + mapBox.height * y);
      if (await page.locator(".road-choice-list button").count()) await page.locator(".road-choice-list button").first().click({ timeout: 1500 }).catch(() => {});
      if (await page.locator(".map-selection strong").count()) { mapSelected = true; break; }
    }
    if (mapSelected) break;
  }
  if (!mapSelected) throw new Error("Roads could not be selected by clicking the map");
  await page.getByRole("button", { name: "Run baseline", exact: true }).click();
  await page.getByRole("button", { name: "50×" }).click();
  await page.waitForFunction(() => document.querySelector(".study-progress li:first-child small")?.textContent === "Complete", null, { timeout: 60000 });
  const roadResponse = await page.request.get(`${process.env.API_URL ?? "http://localhost:8000"}/api/v1/regions/toronto-demo/roads`);
  const roadData = await roadResponse.json();
  const closable = roadData.features.find((feature) => feature.properties.simulatable && feature.properties.name !== "Unnamed road" && roadData.features.filter((item) => item.properties.name === feature.properties.name).every((item) => item.properties.simulatable));
  if (!closable) throw new Error("Demo network has no closable road");
  await page.locator("#map-road-search").fill(closable.properties.name);
  await page.locator(".map-road-results button").first().click();
  await page.getByRole("button", { name: "Close this road" }).click();
  const uniqueName = `Browser closure ${Date.now()}`;
  await page.locator("#scenario-name").fill(uniqueName);
  await page.locator(".study-task").getByRole("button", { name: "Save change and run" }).click();
  await page.waitForFunction((name) => document.querySelector("#scenario-select option:checked")?.textContent === name, uniqueName);
  const selectedName = await page.locator("#scenario-select option:checked").innerText();
  if (selectedName !== uniqueName) throw new Error(`Saved scenario mismatch: ${selectedName}`);
  await page.getByRole("slider", { name: "Comparison replay time" }).waitFor({ timeout: 60000 });
  const apiBase = process.env.API_URL ?? "http://localhost:8000";
  const savedScenarios = await (await page.request.get(`${apiBase}/api/v1/scenarios`)).json();
  const savedScenario = savedScenarios.find((scenario) => scenario.name === uniqueName);
  const replayResponse = await page.request.get(`${apiBase}/api/v1/scenarios/${savedScenario.id}/runs`);
  const latestRun = (await replayResponse.json())[0];
  const frames = await (await page.request.get(`${process.env.API_URL ?? "http://localhost:8000"}/api/v1/runs/${latestRun.id}/replay`)).json();
  if (!frames.some((frame) => frame.road_traffic?.length)) throw new Error("Run replay has no observed road traffic");
  const occupiedFrame = frames.findIndex((frame) => frame.road_traffic?.length);
  await page.getByRole("slider", { name: "Comparison replay time" }).fill(String(frames[occupiedFrame].time));
  await page.getByText("Colors show traffic in this simulation; gray roads have no traffic reading").waitFor();
  await page.getByRole("region", { name: `Before and after on ${closable.properties.name}` }).waitFor();
  if (errors.length) throw new Error(`Browser errors: ${errors.join(" | ")}`);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator("#map-road-search").fill(closable.properties.name);
  await page.locator(".map-road-results button").first().click();
  await page.getByText("Map key", { exact: true }).waitFor();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  if (overflow) throw new Error("Mobile page has horizontal overflow");
  await page.locator("#region-select").selectOption("vancouver-demo");
  await page.getByRole("button", { name: "Run baseline", exact: true }).waitFor();
  await page.getByRole("button", { name: "Run baseline", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".study-progress li:first-child small")?.textContent === "Complete", null, { timeout: 60000 });
  await page.locator("#demand-profile").selectOption("high");
  await page.getByText("You changed this study. Save it as a new scenario before running the change.").waitFor();
  if (await page.getByRole("button", { name: "Run simulation" }).isEnabled()) throw new Error("Run should be disabled while scenario edits are unsaved");
  await page.locator(".study-task").getByRole("button", { name: "Save change and run" }).click();
  await page.waitForFunction(() => document.querySelector(".study-progress li:nth-child(2) small")?.textContent === "Complete", null, { timeout: 60000 });
  await page.getByRole("region", { name: "Compare traffic on the map" }).waitFor();
  await page.getByRole("region", { name: "Comparison evidence" }).getByText("Traffic pattern").waitFor();
  await page.getByRole("region", { name: "Comparison evidence" }).getByText(/Demand settings differ/).waitFor();
  await page.getByRole("button", { name: "Baseline", exact: true }).click();
  await page.getByText("BASELINE MAP REPLAY").waitFor();
  await page.getByRole("slider", { name: "Comparison replay time" }).fill("30");
  await page.getByRole("button", { name: "With change" }).click();
  await page.getByText("WITH CHANGE MAP REPLAY").waitFor();
  await page.getByRole("button", { name: "Side by side" }).click();
  if (await page.locator(".comparison-map-grid .maplibregl-canvas").count() !== 2) throw new Error("Before/after maps did not render together");
  if ((await page.locator(".comparison-map-label strong").allTextContents()).join(" / ") !== "Baseline / With change") throw new Error("Comparison maps have the wrong labels");
  const vancouverRoads = await (await page.request.get(`${process.env.API_URL ?? "http://localhost:8000"}/api/v1/regions/vancouver-demo/roads`)).json();
  const comparisonRoad = vancouverRoads.features.find((feature) => feature.properties.simulatable && feature.properties.name !== "Unnamed road");
  await page.locator("#map-road-search").fill(comparisonRoad.properties.name);
  await page.locator(".map-road-results button").first().click();
  await page.getByRole("region", { name: `Before and after on ${comparisonRoad.properties.name}` }).waitFor();
  await page.getByRole("button", { name: "One map" }).click();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download results" }).click();
  const download = await downloadPromise;
  if (!download.suggestedFilename().endsWith("-comparison.json")) throw new Error("Comparison export filename is missing");
  const exported = JSON.parse(await readFile(await download.path(), "utf8"));
  if (!exported.changes?.some((change) => change.label === "Traffic pattern") || !exported.provenance?.baseline?.network_version) throw new Error("Comparison export is missing changes or provenance");
  const comparisonName = `Vancouver demand study ${Date.now()}`;
  await page.getByRole("textbox", { name: "Comparison name" }).fill(comparisonName);
  await page.getByRole("button", { name: "Save comparison" }).click();
  await page.getByRole("textbox", { name: "Comparison link" }).waitFor();
  const studyLink = await page.getByRole("textbox", { name: "Comparison link" }).inputValue();
  if (!studyLink.includes("?study=")) throw new Error("Saved comparison has no reopen link");
  await page.goto(studyLink, { waitUntil: "domcontentloaded" });
  await page.getByRole("region", { name: "Compare traffic on the map" }).waitFor();
  await page.getByRole("region", { name: "Save comparison" }).getByText(comparisonName, { exact: true }).waitFor();
  if (await page.locator("#region-select").inputValue() !== "vancouver-demo") throw new Error("Saved comparison reopened in the wrong district");
  await page.getByRole("button", { name: "Open comparison" }).click();
  await page.getByRole("heading", { name: "Compare runs" }).waitFor();
  await page.getByText("What changed", { exact: true }).waitFor();
  await page.getByRole("region", { name: "Comparison evidence" }).getByText("Run dates and model data").click();
  await page.getByText("Road data version").first().waitFor();
  await page.getByText("Run comparison").waitFor();
  await page.reload();
  await page.getByRole("button", { name: "Open comparison" }).waitFor();
  await page.getByRole("button", { name: "Start a new study in Vancouver" }).click();
  await page.getByRole("button", { name: "Run baseline", exact: true }).waitFor();
  if (new URL(page.url()).searchParams.has("study")) throw new Error("New study retained the saved comparison URL");
  if (await page.locator("#region-select").inputValue() !== "vancouver-demo") throw new Error("New study changed the district");
  await page.getByRole("button", { name: "Run baseline", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".study-progress li:first-child small")?.textContent === "Complete", null, { timeout: 60000 });
  await page.locator(".quick-change-grid button").filter({ hasText: "More traffic" }).click();
  await page.locator(".task-change").getByText(/Traffic amount: 1\.0/).waitFor();
  await page.locator(".study-task").getByRole("button", { name: "Save change and run" }).click();
  await page.waitForFunction(() => document.querySelector(".study-progress li:nth-child(2) small")?.textContent === "Complete", null, { timeout: 60000 });
  await page.locator(".study-task").getByRole("button", { name: "View paired maps" }).click();
  if (await page.locator(".comparison-map-grid .maplibregl-canvas").count() !== 2) throw new Error("Guided study did not show paired maps");
  await page.locator(".saved-studies summary").click();
  await page.locator(".saved-studies-list").getByText(comparisonName, { exact: true }).waitFor();
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) throw new Error("Guided study has mobile horizontal overflow");
  await page.getByRole("button", { name: "Start a new study in Vancouver" }).click();
  await page.getByRole("button", { name: "Run baseline", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".study-progress li:first-child small")?.textContent === "Complete", null, { timeout: 60000 });
  await page.locator("#map-road-search").fill(comparisonRoad.properties.name);
  await page.locator(".map-road-results button").first().click();
  await page.getByRole("region", { name: "Selected road" }).getByRole("combobox", { name: "Speed cap on selected road" }).selectOption("0.5");
  await page.locator(".task-change").getByText(/Speed cap on/).waitFor();
  await page.locator(".study-task").getByRole("button", { name: "Save change and run" }).click();
  await page.waitForFunction(() => document.querySelector(".study-progress li:nth-child(2) small")?.textContent === "Complete", null, { timeout: 60000 });
  await page.getByRole("region", { name: "Comparison evidence" }).getByText(/Speed cap:/).waitFor();
  const speedScenarioId = await page.locator("#scenario-select").inputValue();
  const speedRuns = await (await page.request.get(`${apiBase}/api/v1/scenarios/${speedScenarioId}/runs`)).json();
  const speedRunResponse = await page.request.get(`${apiBase}/api/v1/runs/${speedRuns[0].id}`);
  const speedRun = await speedRunResponse.json();
  if (speedRun.stage !== "completed" || speedRun.metrics.reduced_speed_edges < 1) throw new Error("Speed cap did not reach the SUMO worker");
  console.log("Browser study workflow passed: area search, map, closure, saved comparison, new study, guided change, road speed cap, paired maps, mobile width.");
} finally {
  await browser.close();
}
